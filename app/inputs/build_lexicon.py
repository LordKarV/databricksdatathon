"""Build app/inputs/lexicon.json from the taxonomy (kb/taxonomy/services.json) for the 7 app services.

Run from the repo root: .venv-app/bin/python app/inputs/build_lexicon.py
The output is committed (the deploy bundle has no kb/taxonomy) and shipped in the app shell, so the search box and
the server parser use the same phrases. Sources per service: names (en, hi, mr), name_phrases and symptom_phrases
whose route or second card is the service. A parenthesised gloss ("peeliya (jaundice) wala bachcha") yields both
the phrase without it and the gloss word alone is not added (too broad).
The danger words (inputs/understand.py) ship too, so the browser checks them before any model call.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "app"))
from inputs.understand import DANGER  # noqa: E402, RUF100

OUT = Path(__file__).resolve().parent / "lexicon.json"
APP_KEY = {"trauma_care": "trauma_emergency", "emergency_csection": "emergency_csection", "nicu": "nicu",
           "burn_care": "burn_care", "dialysis": "dialysis", "mri": "mri", "cardiac_surgery": "cardiac_surgery"}
# Phrases from the earlier app stub and the feasibility tests that the taxonomy does not carry.
EXTRA = {
    "emergency_csection": ["caesarean", "cesarean", "lscs", "c section", "सिजेरियन", "बच्चा उल्टा"],
    "nicu": ["newborn icu", "navjaat icu", "baby icu", "premature", "समय से पहले"],
    "trauma_emergency": ["accident", "chot", "fracture", "head injury", "haddi toot", "दुर्घटना", "एक्सीडेंट", "चोट"],
    "burn_care": ["burn", "burns", "jal gaya", "jal gayi", "jalna", "जल गया", "जल गई", "जलना"],
    "dialysis": ["kidney machine", "khoon saaf", "डायलिसिस"],
    "mri": ["mri", "एमआरआई"],
    "cardiac_surgery": ["bypass", "valve replacement", "cabg", "dil ka operation", "दिल का ऑपरेशन", "वाल्व"],
}


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s.casefold()).strip()


def variants(phrase: str) -> list[str]:
    out = [phrase]
    if "(" in phrase:
        out.append(re.sub(r"\s*\([^)]*\)", "", phrase))
    return [norm(v) for v in out if len(norm(v)) >= 3]


def main() -> None:
    tax = json.loads((ROOT / "kb" / "taxonomy" / "services.json").read_text())
    lex: dict[str, set[str]] = {k: set() for k in APP_KEY.values()}
    for cat in tax["categories"]:
        for s in cat["services"]:
            key = APP_KEY.get(s["id"])
            if key:
                for names in s["names"].values():
                    for n in names:
                        lex[key].update(variants(n))
                for n in s.get("name_phrases") or []:
                    lex[key].update(variants(n))
            for sp in s.get("symptom_phrases") or []:
                for target in (sp.get("route"), sp.get("second_card")):
                    if target in APP_KEY:
                        lex[APP_KEY[target]].update(variants(sp["phrase"]))
                        break
    for key, words in EXTRA.items():
        lex[key].update(norm(w) for w in words)
    lex["emergency_csection"] -= {"fru"}  # three letters, matches inside other words
    doc = {"about": "Generated by app/inputs/build_lexicon.py from kb/taxonomy/services.json; do not edit.",
           "services": {k: sorted(v) for k, v in lex.items()},
           "danger": [norm(w) for w in DANGER], "planned": ["mri", "cardiac_surgery"]}
    OUT.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n")
    print(f"{sum(map(len, lex.values()))} phrases for {len(lex)} services -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
