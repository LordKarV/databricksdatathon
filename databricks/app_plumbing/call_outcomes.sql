CREATE TABLE IF NOT EXISTS workspace.referral_saathi.call_outcomes (
  outcome_id STRING NOT NULL COMMENT 'Random UUID for this outcome report, generated by the app',
  facility_id STRING COMMENT 'Facility the caller phoned (unique_id in facility_trust and the other facility tables)',
  service_id STRING COMMENT 'Service the caller asked about (services.service_id)',
  outcome STRING COMMENT 'Answer to "did they confirm the service?": yes, no or no_answer',
  questions ARRAY<STRING> COMMENT 'Ids or text of the suggested call questions shown to the caller; never free-text notes about a patient',
  model_version STRING COMMENT 'Ranking model version that produced the recommendation',
  district STRING COMMENT 'Coarse district name of the search (LGD district). Never raw GPS, PIN or address',
  created_at TIMESTAMP COMMENT 'When the app recorded the outcome (UTC)',
  app_version STRING COMMENT 'Deployed app version that wrote the row'
)
USING DELTA
COMMENT 'Call outcomes for the learning loop (issue #65): after a referral, the caller reports whether the facility confirmed the service. Written only by the referral-saathi app. NO PATIENT DATA MAY BE STORED: no names, phone numbers, ages, conditions, free-text notes, raw GPS or addresses. District is the finest location allowed.'
;
-- CHECK constraints are only accepted as ALTER on Delta, not inline in CREATE.
ALTER TABLE workspace.referral_saathi.call_outcomes ADD CONSTRAINT outcome_valid CHECK (outcome IN ('yes', 'no', 'no_answer'))
